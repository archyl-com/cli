package tour

import (
	"strconv"
	"strings"

	"github.com/archyl-com/cli/internal/diagram"
	"github.com/archyl-com/cli/internal/graph"
)

// MaxDiagramNodes keeps a stop's diagram readable: the stop and its most
// connected neighbours.
const MaxDiagramNodes = 12

// MarkdownOptions shape the Markdown form.
type MarkdownOptions struct {
	// Diagrams adds a Mermaid diagram centred on each stop, for a document
	// such as ONBOARDING.md. Agents read the tour without them.
	Diagrams bool
}

// Markdown renders the tour as one document.
func Markdown(t *Tour, g *graph.Graph, opts MarkdownOptions) string {
	var b strings.Builder
	elements := 0
	for _, s := range t.Stops {
		if s.Kind == KindElement {
			elements++
		}
	}
	title := "Tour of " + t.Project
	if t.FocusID != "" && len(t.Stops) > 0 {
		title = "Tour of " + t.Stops[0].Name
	}
	b.WriteString("# " + title + "\n\n")
	b.WriteString("A walk through the architecture in " + strconv.Itoa(elements) + " stops, in the order work flows. ")
	b.WriteString("Generated by `archyl tour` from the model in Archyl")
	if t.Narrated {
		b.WriteString("; the story is written by AI from that model")
	}
	b.WriteString(".\n")

	n := 0
	for _, s := range t.Stops {
		switch s.Kind {
		case KindOverview:
			b.WriteString("\n## The big picture\n\n")
			writeOverview(&b, s)
			if opts.Diagrams && g != nil {
				writeDiagram(&b, g, s.ElementID)
			}
		case KindElement:
			n++
			b.WriteString("\n## " + strconv.Itoa(n) + ". " + s.Name + "\n\n")
			writeElement(&b, s)
			if opts.Diagrams && g != nil {
				writeDiagram(&b, g, s.ElementID)
			}
		case KindRecap:
			b.WriteString("\n## Recap\n\n")
			writeRecap(&b, t)
		}
	}
	return b.String()
}

func writeOverview(b *strings.Builder, s Stop) {
	if s.Level != "" {
		b.WriteString("*" + Describe(s) + "*\n\n")
	}
	switch {
	case s.Story != "":
		b.WriteString(s.Story + "\n\n")
	case s.Description != "":
		b.WriteString(s.Description + "\n\n")
	}
	if len(s.Flows) > 0 {
		b.WriteString("**Main flows**\n\n")
		for _, f := range s.Flows {
			b.WriteString("- " + f + "\n")
		}
		b.WriteString("\n")
	}
	if len(s.Systems) > 0 {
		b.WriteString("- **Systems:** " + strings.Join(s.Systems, ", ") + "\n")
	}
	if len(s.People) > 0 {
		b.WriteString("- **Used by:** " + strings.Join(s.People, ", ") + "\n")
	}
	if len(s.Externals) > 0 {
		b.WriteString("- **Relies on:** " + capped(s.Externals, 10) + "\n")
	}
	if len(s.Infrastructure) > 0 {
		b.WriteString("- **Shared infrastructure:** " + capped(s.Infrastructure, 10) + "\n")
	}
	if c := s.Counts; len(c) > 0 {
		b.WriteString("- **Model:** " + countLine(c) + "\n")
	}
	writeFacts(b, s)
}

func writeElement(b *strings.Builder, s Stop) {
	b.WriteString("*" + Describe(s) + "*\n\n")
	if s.Story != "" {
		b.WriteString(s.Story + "\n\n")
	} else if s.Why != "" {
		b.WriteString("**Why it's here:** " + s.Why + "\n\n")
	}
	if s.Description != "" {
		b.WriteString("> " + s.Description + "\n\n")
	}
	if len(s.KeyParts) > 0 {
		names := make([]string, len(s.KeyParts))
		for i, p := range s.KeyParts {
			names[i] = p.Name
		}
		line := strings.Join(names, ", ")
		if s.More > 0 {
			line += " and " + strconv.Itoa(s.More) + " more"
		}
		b.WriteString("- **Key parts:** " + line + "\n")
	}
	if len(s.UsedBy) > 0 {
		b.WriteString("- **Used by:** " + Links(s.UsedBy, s.UsedByMore) + "\n")
	}
	if len(s.Uses) > 0 {
		b.WriteString("- **Uses:** " + Links(s.Uses, s.UsesMore) + "\n")
	}
	if len(s.Infrastructure) > 0 {
		b.WriteString("- **Infrastructure:** " + capped(s.Infrastructure, 8) + "\n")
	}
	writeFacts(b, s)
}

// writeFacts writes what the API added: owners, files, decisions, notes and
// rules.
func writeFacts(b *strings.Builder, s Stop) {
	if len(s.Owners) > 0 {
		b.WriteString("- **Owned by:** " + strings.Join(s.Owners, ", ") + "\n")
	}
	if len(s.Files) > 0 {
		b.WriteString("\n**Start here**\n\n")
		for _, f := range s.Files {
			b.WriteString("- `" + f.Path + "`: " + f.Reason + "\n")
		}
	}
	if len(s.Decisions) > 0 {
		b.WriteString("\n**Decisions**\n\n")
		for _, d := range s.Decisions {
			b.WriteString("- ADR-" + strconv.Itoa(d.Number) + " " + d.Title + " (" + d.Status + ")\n")
		}
	}
	if len(s.Notes) > 0 {
		b.WriteString("\n**Good to know**\n\n")
		for _, n := range s.Notes {
			b.WriteString("- " + n.Kind + ": " + clip(n.Text, 200) + "\n")
		}
	}
	if len(s.Rules) > 0 {
		b.WriteString("\n**Rules that guard it**\n\n")
		for _, r := range s.Rules {
			b.WriteString("- " + r.Name + " (" + r.Severity + ")\n")
		}
	}
}

func writeRecap(b *strings.Builder, t *Tour) {
	var names []string
	for _, s := range t.Stops {
		if s.Kind == KindElement {
			names = append(names, s.Name)
		}
	}
	if len(names) > 0 {
		b.WriteString("You met " + strings.Join(names, ", ") + ".\n\n")
	}
	switch {
	case t.TraceTask != "":
		b.WriteString("**Try it:** " + t.TraceTask + "\n\n")
	case len(t.Trace) > 0:
		b.WriteString("**Try it:** follow one piece of work through the code: " + strings.Join(t.Trace, " → ") + ".\n\n")
	}
	b.WriteString("Next: `archyl brief <files>` before you change code, `archyl why <file>` when something surprises you, `archyl map` to explore.\n")
}

func writeDiagram(b *strings.Builder, g *graph.Graph, id string) {
	v := StopView(g, id)
	if v == nil {
		return
	}
	b.WriteString("\n```mermaid\n" + diagram.Mermaid(v, v.Hops()) + "```\n")
}

// StopView is the diagram of a stop: centred on its element, without shared
// infrastructure, and trimmed to its most connected neighbours, or the
// system context for the overview of a whole model. Nil when there is nothing worth drawing.
func StopView(g *graph.Graph, id string) *diagram.View {
	v := diagram.For(g, nil)
	if n := g.Node(id); n != nil {
		v = diagram.Focus(g, n, 1)
	}
	v = diagram.Drop(v, func(box diagram.Node) bool {
		n := g.Node(box.ID)
		return n != nil && box.ID != id && Infra(n)
	})
	v = diagram.Trim(v, MaxDiagramNodes)
	if len(v.Nodes) < 2 {
		return nil
	}
	return v
}

// Describe is a stop's type, technologies and place, on one line.
func Describe(s Stop) string {
	var parts []string
	kind := strings.ReplaceAll(s.Type, "_", " ")
	if kind == "" {
		kind = s.Level
	}
	if kind != "" {
		parts = append(parts, kind)
	}
	if len(s.Tech) > 0 {
		parts = append(parts, strings.Join(s.Tech[:min(len(s.Tech), 4)], ", "))
	}
	if s.Path != "" && s.Path != s.Name {
		parts = append(parts, "in "+strings.TrimSuffix(s.Path, " / "+s.Name))
	}
	return strings.Join(parts, " · ")
}

// Links writes relationships as "Name (label)", with how many were left
// out.
func Links(list []Link, more int) string {
	parts := make([]string, 0, len(list)+1)
	for _, l := range list {
		if l.Label != "" {
			parts = append(parts, l.Name+" ("+l.Label+")")
		} else {
			parts = append(parts, l.Name)
		}
	}
	if more > 0 {
		parts = append(parts, "and "+strconv.Itoa(more)+" more")
	}
	return strings.Join(parts, ", ")
}

func capped(items []string, n int) string {
	if len(items) <= n {
		return strings.Join(items, ", ")
	}
	return strings.Join(items[:n], ", ") + " and " + strconv.Itoa(len(items)-n) + " more"
}

func countLine(c map[string]int) string {
	var parts []string
	for _, level := range []string{"system", "container", "component", "code"} {
		if n := c[level]; n > 0 {
			word := level
			if level == "code" {
				word = "code element"
			}
			parts = append(parts, strconv.Itoa(n)+" "+plural(word, n))
		}
	}
	return strings.Join(parts, ", ")
}
