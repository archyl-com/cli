package codeowners

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

const (
	// BeginMarker opens the generated block.
	BeginMarker = "# BEGIN archyl codeowners — generated by archyl codeowners, do not edit"
	// EndMarker closes it.
	EndMarker = "# END archyl codeowners"

	// beginPrefix finds the block even when the text after it changed.
	beginPrefix = "# BEGIN archyl codeowners"
)

// ErrUnterminatedBlock is returned for a file that opens the block and never
// closes it: replacing up to the end would drop the hand-written lines.
var ErrUnterminatedBlock = errors.New("the archyl codeowners block has no END line")

// Locations are where GitHub and GitLab look for CODEOWNERS, in their order.
var Locations = []string{".github/CODEOWNERS", "CODEOWNERS", "docs/CODEOWNERS", ".gitlab/CODEOWNERS"}

// Locate finds the repository's CODEOWNERS, relative to root. Without one it
// is where the host looks first: .gitlab/ on GitLab, .github/ elsewhere.
func Locate(root string, gitlab bool) (path string, exists bool) {
	for _, candidate := range Locations {
		if info, err := os.Stat(filepath.Join(root, filepath.FromSlash(candidate))); err == nil && !info.IsDir() {
			return candidate, true
		}
	}
	if gitlab {
		return ".gitlab/CODEOWNERS", false
	}
	return ".github/CODEOWNERS", false
}

// Pattern writes a folder as a CODEOWNERS pattern anchored at the root and
// matching everything inside it.
func Pattern(folder string) string {
	return "/" + escape(folder) + "/"
}

// escape backslashes what CODEOWNERS would otherwise read as a separator, a
// comment or a wildcard.
func escape(path string) string {
	var b strings.Builder
	for _, r := range path {
		switch r {
		case ' ', '\t', '#', '*', '?', '[', ']', '!', '\\':
			b.WriteRune('\\')
		}
		b.WriteRune(r)
	}
	return b.String()
}

// Block renders the generated lines between the markers, each preceded by a
// comment naming its elements. It ends with a newline.
func Block(entries []Entry) string {
	var b strings.Builder
	b.WriteString(BeginMarker + "\n")
	for _, e := range entries {
		b.WriteString("# " + describe(e) + "\n")
		b.WriteString(e.Pattern + " " + strings.Join(e.Owners, " ") + "\n")
	}
	b.WriteString(EndMarker + "\n")
	return b.String()
}

func describe(e Entry) string {
	names := make([]string, 0, len(e.Elements))
	for _, el := range e.Elements {
		names = appendUnique(names, el.Name+" ("+el.Level+")")
	}
	text := strings.Join(names, ", ")
	if e.InheritedFrom != "" {
		text += ", owners from " + e.InheritedFrom
	}
	return strings.Join(strings.Fields(text), " ")
}

// Splice puts block into the content of a CODEOWNERS file: in place of the
// existing block, else above the hand-written rules, after the comments
// that head the file. CODEOWNERS applies the last matching line, so rules
// written by hand below the block win over the generated ones. An empty
// block removes the existing one. Line endings follow the file's.
func Splice(content, block string) (string, error) {
	crlf := strings.Contains(content, "\r\n")
	content = strings.ReplaceAll(content, "\r\n", "\n")

	before, after, found, err := split(content)
	if err != nil {
		return "", err
	}
	var out string
	switch {
	case found && block == "":
		// Drop the blank line that separated the block from the rules.
		switch {
		case after == "" && strings.TrimSpace(before) != "":
			before = strings.TrimRight(before, "\n") + "\n"
		case before == "" || strings.HasSuffix(before, "\n\n"):
			after = strings.TrimPrefix(after, "\n")
		}
		out = before + after
	case found:
		out = before + block + after
	case block == "":
		out = content
	default:
		out = insert(content, block)
	}
	if crlf {
		out = strings.ReplaceAll(out, "\n", "\r\n")
	}
	return out, nil
}

// insert places a new block before the first rule, GitLab [Section] headers
// included, after the last blank line of the comments above it: a comment
// right above a rule describes that rule and stays with it. A file without
// rules gets the block at its end.
func insert(content, block string) string {
	if strings.TrimSpace(content) == "" {
		return block
	}
	lines := strings.SplitAfter(content, "\n")
	at, offset := 0, 0
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		switch {
		case trimmed == "":
			at = offset + len(line)
		case !strings.HasPrefix(trimmed, "#"):
			return content[:at] + block + "\n" + content[at:]
		}
		offset += len(line)
	}
	return strings.TrimRight(content, "\n") + "\n\n" + block
}

// Equal reports whether two CODEOWNERS texts hold the same lines, whatever
// their line endings and final newline.
func Equal(a, b string) bool {
	return slices.Equal(lines(a), lines(b))
}

// split cuts content around its block, markers included.
func split(content string) (before, after string, found bool, err error) {
	lines := strings.SplitAfter(content, "\n")
	start := -1
	offset := 0
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		switch {
		case start < 0 && strings.HasPrefix(trimmed, beginPrefix):
			start = offset
		case start >= 0 && trimmed == EndMarker:
			return content[:start], content[offset+len(line):], true, nil
		}
		offset += len(line)
	}
	if start >= 0 {
		return "", "", false, fmt.Errorf("%w; delete the block or add %q after it", ErrUnterminatedBlock, EndMarker)
	}
	return content, "", false, nil
}
