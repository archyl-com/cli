func TestFromImpact(
	t *testing.T,
) {
	impact := &api.LocateResult{Impact: &api.BlastRadius{Elements: []api.TouchedElement{
		{
			Element: api.Element{ID: "api", Name: "Orders API", Type: "container", Path: "Shop / Orders API"},
			Dependents: []api.ImpactedElement{
				{Element: api.Element{Name: "Storefront"}},
				{Element: api.Element{Name: "Admin"}},
			},
		},
		{Element: api.Element{ID: "db", Name: "Orders DB", Type: "container"}},
	}}}

	testCases := []struct {
		name   string
		result *api.LocateResult
		want   []Touched
	}{
		{name: "no result", result: nil, want: nil},
		{name: "no impact", result: &api.LocateResult{}, want: nil},
		{
			name: "names from the model are stripped of control characters",
			result: &api.LocateResult{Impact: &api.BlastRadius{Elements: []api.TouchedElement{{
				Element:    api.Element{ID: "x", Name: "Orders\x1b[2J API", Type: "container"},
				Dependents: []api.ImpactedElement{{Element: api.Element{Name: "Web\x07"}}},
			}}}},
			want: []Touched{{Element: Element{ID: "x", Name: "Orders[2J API", Type: "container"}, UsedBy: []string{"Web"}}},
		},
		{
			name:   "elements with their dependents",
			result: impact,
			want: []Touched{
				{Element: Element{ID: "api", Name: "Orders API", Type: "container", Path: "Shop / Orders API"}, UsedBy: []string{"Storefront", "Admin"}},
				{Element: Element{ID: "db", Name: "Orders DB", Type: "container"}},
			},
		},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			assert.Equal(t, testCase.want, FromImpact(testCase.result))
		})
	}
}

