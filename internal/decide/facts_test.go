func TestDiffRank(
	t *testing.T,
) {
	testCases := []struct {
		name string
		diff repo.FileDiff
		want int
	}{
		{name: "source", diff: repo.FileDiff{Path: "internal/orders/service.go"}, want: 0},
		{name: "a directory that only contains test", diff: repo.FileDiff{Path: "contest/latest/run.go"}, want: 0},
		{name: "go test", diff: repo.FileDiff{Path: "internal/orders/service_test.go"}, want: 1},
		{name: "js spec", diff: repo.FileDiff{Path: "web/src/cart.spec.ts"}, want: 1},
		{name: "python test", diff: repo.FileDiff{Path: "app/test_orders.py"}, want: 1},
		{name: "tests directory", diff: repo.FileDiff{Path: "tests/integration/orders.rb"}, want: 1},
		{name: "testdata", diff: repo.FileDiff{Path: "internal/x/testdata/in.json"}, want: 1},
		{name: "lock file", diff: repo.FileDiff{Path: "web/package-lock.json"}, want: 2},
		{name: "go.sum", diff: repo.FileDiff{Path: "go.sum"}, want: 2},
		{name: "protobuf", diff: repo.FileDiff{Path: "gen/orders.pb.go"}, want: 2},
		{name: "vendored", diff: repo.FileDiff{Path: "vendor/github.com/x/y.go"}, want: 2},
		{name: "nested node_modules", diff: repo.FileDiff{Path: "web/node_modules/a/index.js"}, want: 2},
		{
			name: "generated header",
			diff: repo.FileDiff{Path: "internal/db/models.go", Text: "+// Code generated by sqlc. DO NOT EDIT.\n"},
			want: 2,
		},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			assert.Equal(t, testCase.want, diffRank(testCase.diff))
		})
	}
}

func TestTrimDiff(
	t *testing.T,
) {
	source := repo.FileDiff{Path: "orders.go", Text: "diff --git a/orders.go b/orders.go\n+source\n"}
	test := repo.FileDiff{Path: "orders_test.go", Text: "diff --git a/orders_test.go b/orders_test.go\n+test\n"}
	lock := repo.FileDiff{Path: "go.sum", Text: "diff --git a/go.sum b/go.sum\n+sum\n"}
	big := repo.FileDiff{Path: "big.go", Text: "diff --git a/big.go b/big.go\n" + strings.Repeat("+line of code\n", 200)}

	testCases := []struct {
		name        string
		diffs       []repo.FileDiff
		limit       int
		want        []string
		wantMissing []string
		wantOrder   []string
	}{
		{name: "nothing", diffs: nil, limit: 100},
		{
			name:      "everything fits, source first",
			diffs:     []repo.FileDiff{lock, test, source},
			limit:     DiffLimit,
			want:      []string{"+source", "+test", "+sum"},
			wantOrder: []string{"+source", "+test", "+sum"},
		},
		{
			name:        "a file too big is cut at a line",
			diffs:       []repo.FileDiff{big},
			limit:       1024,
			want:        []string{"+line of code\n", truncatedNote},
			wantMissing: []string{"(diff left out for"},
		},
		{
			name:        "no room left: files are only named",
			diffs:       []repo.FileDiff{source, test, lock},
			limit:       len(source.Text),
			want:        []string{"+source", "(diff left out for: orders_test.go, go.sum)"},
			wantMissing: []string{"+test", "+sum"},
		},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			got := TrimDiff(testCase.diffs, testCase.limit)
			for _, w := range testCase.want {
				assert.Contains(t, got, w)
			}
			for _, w := range testCase.wantMissing {
				assert.NotContains(t, got, w)
			}
			last := -1
			for _, w := range testCase.wantOrder {
				i := strings.Index(got, w)
				assert.Greater(t, i, last, "%q out of order", w)
				last = i
			}
			if strings.Contains(got, truncatedNote) {
				assert.LessOrEqual(t, len(got), testCase.limit)
			}
		})
	}
}

func TestCutAtLine(
	t *testing.T,
) {
	testCases := []struct {
		name string
		s    string
		n    int
		want string
	}{
		{name: "fits", s: "a\nb\n", n: 10, want: "a\nb\n"},
		{name: "cut at a line end", s: "aaa\nbbb\n", n: 6, want: "aaa\n"},
		{name: "no line end in reach", s: "aaaaaa", n: 3, want: "aa\n"},
		{name: "never inside a character", s: "ééé", n: 4, want: "é\n"},
		{name: "never inside a character before a line end", s: "a\nééé", n: 5, want: "a\n"},
		{name: "one character too wide", s: "日本", n: 2, want: ""},
		{name: "no room", s: "abc", n: 0, want: ""},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			assert.Equal(t, testCase.want, cutAtLine(testCase.s, testCase.n))
		})
	}
}
